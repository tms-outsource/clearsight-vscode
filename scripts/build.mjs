function semanticColors(c, italic) {
  const style = (foreground, extra = {}) => ({ foreground, ...extra });
  return {
    namespace: c.type,
    class: c.type,
    interface: c.type,
    enum: c.type,
    struct: c.type,
    type: c.type,
    typeParameter: c.type,
    'class.defaultLibrary': c.type,
    function: c.function,
    method: c.function,
    macro: c.function,
    decorator: c.function,
    parameter: italic ? style(c.parameter, { italic: true }) : c.parameter,
    variable: c.fg,
    'variable.defaultLibrary': c.fg,
    property: c.property,
    enumMember: c.number,
    event: c.property,
    keyword: c.keyword,
    selfKeyword: italic ? style(c.keyword, { italic: true }) : c.keyword,
    selfParameter: italic ? style(c.keyword, { italic: true }) : c.keyword,
    string: c.string,
    number: c.number,
    regexp: c.regex,
    operator: c.operator,
    comment: italic ? style(c.comment, { italic: true }) : c.comment,
    label: c.keyword,
    lifetime: c.type,
    '*.deprecated': { strikethrough: true },
  };
}

const palette = loadPalette();
const outDir = join(ROOT, 'themes');
mkdirSync(outDir, { recursive: true });
const contributes = [];
for (const v of Object.values(palette.variants)) {
  for (const italic of [true, false]) {
    const label = italic ? v.label : `${v.label} No Italics`;
    const file = `${label.toLowerCase().replace(/\s+/g, '-')}-color-theme.json`;
    const theme = {
      $schema: 'vscode://schemas/color-theme',
      name: label,
      type: v.type,
      semanticHighlighting: true,
      colors: uiColors(v.colors, v),
      tokenColors: tokenColors(v.colors, italic),
      semanticTokenColors: semanticColors(v.colors, italic),
    };
    writeFileSync(join(outDir, file), JSON.stringify(theme, null, 2) + '\n');
    contributes.push({ label, uiTheme: v.type === 'dark' ? 'vs-dark' : 'vs', path: `./themes/${file}` });
  }
}

const pkgPath = join(ROOT, 'package.json');
const { readFileSync } = await import('node:fs');
const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
pkg.contributes = { themes: contributes };
writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
console.log(`${contributes.length} themes written to themes/`);
